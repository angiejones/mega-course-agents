import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { Agent } from '@mastra/core/agent';
import { settings } from '../packages/config.ts';
import { createInvestigation, deliveryInstructions } from '../agents/delivery/src/service.ts';
import { deliveryRecords, type DeliveryRecord } from '../agents/delivery/src/records.ts';
const directory = resolve('data/delivery-reasoning-verification', randomUUID());
mkdirSync(directory, {recursive:true});
const evidence: unknown[] = [];
async function run(records: readonly DeliveryRecord[], clarifications: {question:string;answer:string}[] = []) {
  const request = {trackingId:records[0].trackingId, deadline:new Date(Date.now()+72*3600000).toISOString()};
  const investigation = createInvestigation(request, records);
  const agent = new Agent({id:'delivery-reasoning-check',name:'Delivery investigation',model:settings.smallModel,instructions:deliveryInstructions,tools:investigation.tools});
  const output = await agent.generate(JSON.stringify({request,clarifications}), {maxSteps:6,abortSignal:AbortSignal.timeout(45000)});
  const result = investigation.result();
  evidence.push({request, records, clarifications, toolCalls:output.toolCalls, toolResults:output.toolResults, result});
  writeFileSync(resolve(directory,'evidence.json'), JSON.stringify(evidence,null,2));
  assert(result, 'The model must submit a decision');
  return result;
}
const first = await run(deliveryRecords);
assert.equal(first.state,'input-required');
assert(first.state === 'input-required');
assert.match(first.question,/reception|office|building|address/i);
const uncertain = await run(deliveryRecords,[{question:first.question,answer:"I'm not sure where that is. I haven't checked with anyone."}]);
assert(uncertain.state === 'input-required' || (uncertain.state === 'completed' && (uncertain.data as {outcome:string}).outcome === 'inconclusive'), 'An uncertain customer answer must not establish misdelivery');
const completed = await run(deliveryRecords,[{question:first.question,answer:'My address is a detached house, with no reception desk or staff. The adjacent office is not my address, and nobody there is authorized to accept my parcels.'}]);
assert.equal(completed.state,'completed');
assert(completed.state === 'completed');
assert.equal((completed.data as {outcome:string}).outcome,'too_late');
const gate = [{trackingId:'parcel-gate',intendedDeliveryAddress:'26 Oak Street, Springfield, MA 01103, US',scanLocation:'Property entrance; coordinates are insufficient to identify the house',driverNote:'Left behind the red side gate',photoDescription:'Parcel behind a red wooden gate',recoveryDelayHours:24}];
const alternate = await run(gate);
assert.equal(alternate.state,'input-required');
assert(alternate.state === 'input-required');
assert.match(alternate.question,/gate|entrance/i);
assert.doesNotMatch(alternate.question,/reception/i);
console.log(`Passed: evidence-driven questions, uncertain answer, schedule calculation, different delivery evidence. Saved ${directory}/evidence.json`);
